"""Entry point: python -m lllc  or  the lllc console_script."""

import importlib.util
import os
import subprocess
import sys


def _load_compiler():
    """Import the compiled Python compiler (lllc/compiler.py).

    The file is generated by CI from stdlib/src/Compiler.lll.
    Returns the module, or None if not found.
    """
    p = os.path.join(os.path.dirname(__file__), "compiler.py")
    if not os.path.exists(p):
        return None
    try:
        spec = importlib.util.spec_from_file_location("lllc_compiler", p)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
        return mod
    except Exception:
        return None


def _fallback_binary(args: list[str]) -> None:
    """Delegate to the native binary (downloads on first use)."""
    from lllc._download import ensure_binary

    result = subprocess.run([ensure_binary()] + args)
    sys.exit(result.returncode)


def _find_file(args: list[str]) -> str | None:
    skip = False
    for a in args:
        if skip:
            skip = False
            continue
        if a == "--target":
            skip = True
            continue
        if not a.startswith("-"):
            return a
    return None


def _get_target(args: list[str]) -> str:
    for i, a in enumerate(args):
        if a == "--target" and i + 1 < len(args):
            return args[i + 1]
    return "fs"


def main() -> None:
    args = sys.argv[1:]

    # --binary: pass everything to the native binary directly
    if "--binary" in args:
        _fallback_binary([a for a in args if a != "--binary"])
        return  # not reached

    # --install-binary: download native binary
    if args and args[0] == "--install-binary":
        from lllc._download import ensure_binary

        ensure_binary()
        print("lllc: native binary installed", file=sys.stderr)
        return

    if not args:
        _show_usage()
        sys.exit(1)

    cmd = args[0]
    rest = args[1:]

    if cmd == "check":
        file = _find_file(rest)
        if not file:
            print("lllc check: file argument required", file=sys.stderr)
            sys.exit(1)
        compiler = _load_compiler()
        if compiler is None:
            _fallback_binary(args)
            return
        src = open(file, encoding="utf-8").read()
        errors = compiler.collectAllErrors(src)
        for e in errors:
            print(e, file=sys.stderr)
        sys.exit(1 if errors else 0)

    elif cmd == "build":
        target = _get_target(rest)
        if target != "fs":
            # Non-F# targets need the native binary
            _fallback_binary(args)
            return
        file = _find_file(rest)
        if not file:
            print("lllc build: file argument required", file=sys.stderr)
            sys.exit(1)
        compiler = _load_compiler()
        if compiler is None:
            _fallback_binary(args)
            return
        src = open(file, encoding="utf-8").read()
        errors = compiler.collectAllErrors(src)
        if errors:
            for e in errors:
                print(e, file=sys.stderr)
            sys.exit(1)
        out = compiler.compileWithInfer(src)
        sys.stdout.write(out)

    else:
        # All other subcommands (run, self, mcp, new, …) need native binary
        _fallback_binary(args)


def _show_usage() -> None:
    print(
        """\
lllc — ll-lang compiler (Python/F# backend)

Built-in commands (no native binary required):
  lllc build [--target fs] <file.lll>   compile to F#
  lllc check <file.lll>                  type-check (no output)

Commands requiring native binary:
  lllc build --target ts|py|java|cs|llvm <file>
  lllc run   <file.lll>
  lllc self  <cmd> <file>
  lllc mcp

  lllc --install-binary      download native binary
  lllc --binary <cmd> ...    force native binary for any command"""
    )


if __name__ == "__main__":
    main()
